"""Writes the ticket and booth cards into the HTML pages from site/data/summit-tickets.json.

    python tools/render_tickets.py          rewrite the blocks between the markers
    python tools/render_tickets.py --check  exit 1 if the pages are out of date (run in CI)

The pages stay plain static HTML (no JavaScript is needed to see prices or follow a buy link). Every visible
string lives in STRINGS so a French version can be added by translating one dictionary.
"""
import html
import json
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "site" / "data" / "summit-tickets.json"
TARGETS = {  # marker name -> (page, which kinds go there)
    "tickets": (ROOT / "site" / "summit-tickets.html", ("pass",)),
    "booths": (ROOT / "site" / "exhibitions.html", ("booth", "booth-addon")),
}

STRINGS = {
    "en": {
        "buy": "Buy ticket", "reserve": "Reserve a booth", "add": "Add a pass",
        "on_sale": "On sale", "coming_soon": "Coming soon", "sold_out": "Sold out", "closed": "Sales closed",
        "price_tba": "Price to be announced", "plus_tax": "plus applicable taxes",
        "sales_end": "On sale until {date}", "capacity": "Limited to {n}", "left": "{n} left",
        "test_mode": "Test mode: these links open Stripe's sandbox checkout. No real charge is made. Use card 4242 4242 4242 4242.",
        "updated": "Prices and availability updated {date}.",
        "notify": "Email us to be told when sales open",
    },
    "fr": {},  # TODO: French strings; falls back to English until filled in
}


def t(lang, key, **kw):
    return (STRINGS.get(lang, {}).get(key) or STRINGS["en"][key]).format(**kw)


def nice_date(iso):
    try:
        return date.fromisoformat(iso).strftime("%-d %B %Y") if sys.platform != "win32" else date.fromisoformat(iso).strftime("%d %B %Y").lstrip("0")
    except ValueError:
        return iso


def card(tk, lang, kind_label):
    e = html.escape
    status = tk["status"] if tk.get("url") or tk["status"] != "on_sale" else "coming_soon"
    tag = f'<span class="tag {status.replace("_", "")}">{e(t(lang, status))}</span>'
    if tk.get("price_display"):
        price = f'<p class="price">{e(tk["price_display"])} <small>{e(t(lang, "plus_tax"))}</small></p>'
    else:
        price = f'<p class="price tba">{e(t(lang, "price_tba"))}</p>'
    includes = "".join(f"<li>{e(line)}</li>" for line in tk.get("includes", []))
    meta = []
    if tk.get("sales_end"):
        meta.append(t(lang, "sales_end", date=nice_date(tk["sales_end"])))
    if tk.get("capacity"):
        remaining = tk["capacity"] - int(tk.get("sold") or 0)
        meta.append(t(lang, "left", n=remaining) if 0 < remaining <= max(10, tk["capacity"] // 10) else t(lang, "capacity", n=tk["capacity"]))
    meta_html = f'<p class="meta">{e(" · ".join(meta))}</p>' if meta else ""
    if status == "on_sale":
        action = f'<a class="btn" href="{e(tk["url"])}" rel="noopener">{e(kind_label)}</a>'
    elif status == "coming_soon":
        action = f'<a class="btn ghost" href="mailto:{e(SUPPORT)}?subject={e(SUBJECT)}%20{e(tk["key"])}">{e(t(lang, "notify"))}</a>'
    else:
        action = f'<span class="btn disabled" aria-disabled="true">{e(t(lang, status))}</span>'
    return (f'<article class="card ticket" id="t-{e(tk["key"])}">{tag}<h3>{e(tk["name"])}</h3>{price}'
            f'<ul class="ticks">{includes}</ul>{meta_html}{action}</article>')


def render(block, data, lang="en"):
    page, kinds = TARGETS[block]
    items = [tk for tk in data["tickets"] if tk.get("kind") in kinds]
    labels = {"pass": t(lang, "buy"), "booth": t(lang, "reserve"), "booth-addon": t(lang, "add")}
    cards = "\n".join("      " + card(tk, lang, labels[tk["kind"]]) for tk in items)
    out = [f"<!-- {block}:start (generated by tools/render_tickets.py from site/data/summit-tickets.json; do not edit by hand) -->"]
    if not data.get("livemode") and any(tk.get("url") for tk in items):
        out.append(f'    <div class="notice"><b>{html.escape(t(lang, "test_mode"))}</b></div>')
    out.append(f'    <div class="cards tickets">\n{cards}\n    </div>')
    if data.get("generated_at"):
        out.append(f'    <p class="muted updated">{html.escape(t(lang, "updated", date=nice_date(data["generated_at"][:10])))}</p>')
    out.append(f"    <!-- {block}:end -->")
    return "\n".join(out)


def main():
    global SUPPORT, SUBJECT
    check = "--check" in sys.argv
    data = json.loads(DATA.read_text(encoding="utf-8"))
    SUPPORT = data.get("support_email", "shahin.vakilinia@archangx.com")
    SUBJECT = "Tickets:%20Seraphim%20Summit%202027"
    stale = []
    for block, (page, _) in TARGETS.items():
        src = page.read_text(encoding="utf-8")
        pattern = re.compile(rf"<!-- {block}:start.*?<!-- {block}:end -->", re.S)
        if not pattern.search(src):
            sys.exit(f"{page.name}: no <!-- {block}:start --> ... <!-- {block}:end --> markers")
        new = pattern.sub(lambda _m: render(block, data), src)
        if new != src:
            stale.append(page.name)
            if not check:
                page.write_text(new, encoding="utf-8", newline="\n")
    if check and stale:
        print("ticket cards are out of date in: " + ", ".join(stale) + ". Run: python tools/render_tickets.py")
        sys.exit(1)
    print(("up to date: " if check else "rendered: ") + ", ".join(p.name for p, _ in TARGETS.values()) + ("" if stale or check else " (no change)"))


if __name__ == "__main__":
    main()
